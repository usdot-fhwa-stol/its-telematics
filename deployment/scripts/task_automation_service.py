#!/usr/bin/env python3
"""Pipeline engine: runs the deployment steps in a fixed order and aggregates diagnostics on failure."""

import sys
from threading import Event, Thread
from pathlib import Path
from typing import Callable, List, Optional, Sequence, Tuple

from container_orchestrator import ContainerOrchestrator
from host_preparation_service import HostPreparationService
from models import (
    CommandResult,
    SYSTEM_RELATIVE_DIR,
    ExecutionContext,
    InventoryReference,
    TargetProfile,
    TaskExecutionResult,
)

DEFAULT_MANIFEST_REFERENCE = {
    "runtime_env_path": str(SYSTEM_RELATIVE_DIR / ".env"),
    "compose_manifest_paths": [str(SYSTEM_RELATIVE_DIR / "docker-compose.yml")],
}
# Steps whose failure may come from containers that started and then died.
CONTAINER_LOG_STEPS = ("Deploy services",)
REMEDIATION_HINTS = {
    "Verify operating system": (
        "Confirm the host runs a supported Ubuntu LTS release.",
        "Check SSH reachability, the login user, and the private key permissions (chmod 600).",
    ),
    "Install system dependencies": (
        "Confirm the login user can authenticate with sudo and the host can reach its apt mirrors.",
        "Check for a running apt/dpkg process holding the lock.",
    ),
    "Verify registry connectivity": (
        "Check outbound HTTPS access from the host and its DNS settings.",
        "Check security group or firewall rules for registry access.",
    ),
    "Synchronize service manifests": (
        "Verify the .env and secrets were generated by the configuration step.",
        "Check free disk space and write access to telematic_system relative to the remote user's home.",
    ),
    "Remove orphaned containers": ("Check that the Docker daemon is running and accessible to the deployment user.",),
    "Pull container images": (
        "Verify the Docker organization and image tags in .env exist and are accessible.",
        "Check registry rate limits and free disk space.",
    ),
    "Deploy services": (
        "Look for host port conflicts with other processes.",
        "Verify the secrets and variables in .env are correct.",
        "Check Docker daemon health: systemctl status docker.",
    ),
}


class TaskAutomationService:
    """Executes the linear deployment pipeline and stops at the first failing step."""

    def __init__(self, repo_root: Path, manifest_reference: Optional[dict] = None, **options):
        """Store the run configuration.

        Args:
            repo_root: Repository root that manifest paths are relative to.
            manifest_reference: Paths of runtime_env_path and compose_manifest_paths;
                defaults to DEFAULT_MANIFEST_REFERENCE.
            **options: Overrides for remote_workspace, startup_timeout_seconds, prune_volumes,
                log_tail_lines, and registry_endpoints.
        """
        self.repo_root = repo_root
        self.manifest_reference = manifest_reference or DEFAULT_MANIFEST_REFERENCE
        self.options = options
        self.context: Optional[ExecutionContext] = None
        self.host_preparation: Optional[HostPreparationService] = None
        self.orchestrator: Optional[ContainerOrchestrator] = None

    def initialize_execution_context(
        self, target_profiles: Sequence[TargetProfile], inventory: InventoryReference,
    ) -> ExecutionContext:
        """Assemble inputs, manifest references, and the inventory into one immutable context.

        The context is shared by the host preparation service and the container orchestrator,
        which are created here.

        Args:
            target_profiles: Resolved deployment targets.
            inventory: Reference to the generated Ansible inventory.

        Returns:
            The execution context, also stored in self.context.
        """
        self.context = ExecutionContext(
            target_profiles=tuple(target_profiles),
            inventory=inventory,
            manifest_reference=self.manifest_reference,
            repo_root=self.repo_root,
            **self.options,
        )
        self.host_preparation = HostPreparationService(self.context)
        self.orchestrator = ContainerOrchestrator(self.context)
        return self.context

    def dispatch_automation_plan(self) -> TaskExecutionResult:
        """Run each step in order, short-circuiting on the first error or nonzero exit code.

        Returns:
            Successful result listing the completed steps, or the diagnostic result of the
            failing step.

        Raises:
            RuntimeError: If initialize_execution_context has not been called.
        """
        if self.context is None:
            raise RuntimeError("initialize_execution_context must be called before dispatching the plan")
        completed: List[str] = []
        for name, action in self._plan():
            print(f"[{len(completed) + 1}] {name} ", end="", flush=True)
            stop_progress = Event()
            progress = Thread(target=self._show_progress, args=(stop_progress,), daemon=True)
            progress.start()
            try:
                result = action()
            finally:
                stop_progress.set()
                progress.join()
            if not result.success:
                print(f" \033[31mFAILED\033[0m" if sys.stdout.isatty() else " FAILED", flush=True)
                return self.collect_diagnostic_traces(result, tuple(completed))
            print(f" \033[32mOK\033[0m" if sys.stdout.isatty() else " OK", flush=True)
            if result.stdout.strip() and name in ("Verify operating system", "Deploy services"):
                print(result.stdout.strip(), flush=True)
            completed.append(name)
        return TaskExecutionResult(True, tuple(completed))

    @staticmethod
    def _show_progress(stop: Event):
        """Print a dot every half-second until the current pipeline action completes."""
        while not stop.wait(0.5):
            print(".", end="", flush=True)

    def collect_diagnostic_traces(
        self, failed: CommandResult, completed_steps: Tuple[str, ...] = (),
    ) -> TaskExecutionResult:
        """Halt and combine the failure reason, exit code, container log trace, and remediation hints.

        Container logs are collected only for steps in CONTAINER_LOG_STEPS.

        Args:
            failed: Result of the failing step.
            completed_steps: Names of the steps that finished before the failure.

        Returns:
            Failed TaskExecutionResult with the step name, exit code, reason, log trace,
            and remediation hints.
        """
        trace = ""
        if failed.step in CONTAINER_LOG_STEPS:
            trace = self.orchestrator.capture_error_logs()
            # Logs are collected first; then the partially started stack is removed.
            trace += "\n" + self.orchestrator.tear_down_stack().stdout.strip()
        reason = self._failure_reason(failed)
        return TaskExecutionResult(
            False, completed_steps, failed.step, failed.exit_code or 1, reason, trace,
            REMEDIATION_HINTS.get(failed.step, ("Review the Ansible output above.",)),
        )

    @staticmethod
    def _failure_reason(failed: CommandResult) -> str:
        """Return the last 2000 characters of the step output, without Ansible warning lines."""
        lines = (failed.stdout + "\n" + failed.stderr).splitlines()
        useful = [line for line in lines
                  if line.strip() and not line.lstrip().startswith(("[WARNING]", "[DEPRECATION WARNING]"))]
        return "\n".join(useful)[-2000:] or "No error output was captured."

    def _plan(self) -> List[Tuple[str, Callable[[], CommandResult]]]:
        """Return the ordered (step name, action) pairs of the deployment pipeline."""
        return [
            ("Verify operating system", self.host_preparation.verify_operating_system),
            ("Install system dependencies", self.host_preparation.install_system_dependencies),
            ("Verify registry connectivity", self.orchestrator.verify_registry_connectivity),
            ("Synchronize service manifests", self.orchestrator.synchronize_service_manifests),
            ("Remove orphaned containers", self.orchestrator.terminate_orphaned_workloads),
            ("Pull container images", self.orchestrator.pull_managed_images),
            ("Deploy services", self.orchestrator.deploy_service),
        ]
